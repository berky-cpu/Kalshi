# Coinbase / Bitstamp — L3→L2 price-level aggregation, hand-computed.
# ---------------------------------------------------------------------------------------
def test_l3_to_l2_aggregation_sums_orders_at_a_price_level():
    """The single L3→L2 seam: multiple order-ids at one price aggregate to one L2 level."""
    b = OrderIdBook()
    b.add("x1", BID, "100.0", "1.5")
    b.add("x2", BID, "100.0", "2.5")   # same price as x1 → sums to 4.0
    b.add("x3", BID, "99.0", "4.0")
    b.add("y1", ASK, "101.0", "0.5")
    b.add("y2", ASK, "101.0", "0.5")   # sums to 1.0
    assert extract.l2_levels(b, 10) == [
        ("bid", 0, Decimal("100.0"), Decimal("4.0")),
        ("bid", 1, Decimal("99.0"), Decimal("4.0")),
        ("ask", 0, Decimal("101.0"), Decimal("1.0")),
    ]


def test_bitstamp_reconstruction_full_book():
    res = pipeline.normalize_crypto("bitstamp", "live_orders_btcusd",
                                    _records("bitstamp", "live_orders.jsonl"))
    snaps = _snaps(res.books)
    last = snaps[max(snaps)]
    # id101 bid 27000 changed to 0.25; id103 bid 26990@2.00 added; id102 ask deleted.
    assert last == [("bid", 0, "27000.00", "0.25"), ("bid", 1, "26990.00", "2.00")]
    assert res.checkpoint.method == METHOD_DEFERRED


def test_coinbase_l2_reduces_resting_order_on_match():
    res = pipeline.normalize_crypto("coinbase", "full", _records("coinbase", "full.jsonl"))
    snaps = _snaps(res.books)
    # o2 ask opens @1.00 (snap 1) then a match for 0.40 reduces it to 0.60 (snap 2). (Offline the
    # first sequenced frame seeds the baseline, so only post-baseline deltas populate the book.)
    assert snaps[1] == [("ask", 0, "27010.00", "1.00")]
    assert snaps[2] == [("ask", 0, "27010.00", "0.60")]
    assert res.checkpoint.method == METHOD_DEFERRED


# ---------------------------------------------------------------------------------------
# Zero-size L2 levels are dropped (red-team #5).
# ---------------------------------------------------------------------------------------
def test_l2_drops_zero_size_level_after_modify_to_zero():
    b = OrderIdBook()
    b.add("o1", BID, "100.0", "2.0")
    b.add("o2", BID, "99.0", "1.0")
    b.modify("o1", qty="0")  # reduced to 0 WITHOUT a delete — OrderIdBook keeps a (100.0, 0) entry
    rows = extract.l2_levels(b, 10)
    assert "100.0" not in [str(p) for _, _, p, _ in rows]  # the 0-size level must be absent
    assert rows == [("bid", 0, Decimal("99.0"), Decimal("1.0"))]  # and the level re-indexes to 0


