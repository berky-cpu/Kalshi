# Binance — futures pu-chain reconstruction (seeded gap dropped, not silently applied).
# ---------------------------------------------------------------------------------------
def test_binance_reconstruction_drops_the_pu_gap_frame():
    res = pipeline.normalize_crypto("binance", "perp", _records("binance", "depth.jsonl"))
    snaps = _snaps(res.books)
    last = snaps[max(snaps)]
    # events 1-3 apply; event 4 (pu=125 != prev u=120) is a gap → dropped, so 27000 stays 0.5.
    assert last == [
        ("bid", 0, "27000.0", "0.5"), ("bid", 1, "26990.0", "2.0"), ("bid", 2, "26980.0", "4.0"),
        ("ask", 0, "27020.0", "3.0"),
    ]
    assert res.checkpoint.method == METHOD_DEFERRED  # REST-snapshot checkpoint deferred to live
    # exch_ts_ns is populated from the venue event time (E=1000 ms).
    assert res.books[0]["exch_ts_ns"] == 1000 * 1_000_000


