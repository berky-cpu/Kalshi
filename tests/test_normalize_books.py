def test_bybit_reconstruction_before_midstream_snapshot():
    res = pipeline.normalize_crypto("bybit", "perp", _records("bybit", "orderbook.jsonl"))
    snaps = _snaps(res.books)
    # snapshot + 2 deltas: 27010 ask removed, 27020 added; 27000 bid set to 0.5; 26980 added.
    assert snaps[3] == [
        ("bid", 0, "27000.0", "0.5"), ("bid", 1, "26990.0", "2.0"), ("bid", 2, "26980.0", "4.0"),
        ("ask", 0, "27020.0", "3.0"),
    ]
    # the 4th frame is a mid-stream snapshot (reset) → rebuilt book.
    assert snaps[4] == [("bid", 0, "27005.0", "9.0"), ("ask", 0, "27015.0", "1.0")]


def test_bybit_checkpoint_reports_deviation_for_the_reset_snapshot():
    res = pipeline.normalize_crypto("bybit", "perp", _records("bybit", "orderbook.jsonl"))
    cp = res.checkpoint
    assert cp.method == "bybit_snapshot"
    assert cp.n_checkpoints == 1  # only the mid-stream snapshot; the first is the initial build
    # The reset snapshot carries newer data than the reconstruction → non-zero, reported deviation.
    assert cp.n_matches == 0 and cp.n_mismatches == 1
    assert cp.max_deviation == 5.0  # |27020-27015| top-of-book


