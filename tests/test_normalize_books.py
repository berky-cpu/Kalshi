"""L2 reconstruction + checkpoint validation on the recorded fixtures (ROADMAP 2.1 acceptance).

Each venue fixture is replayed through its (reused) recorder ``MessageProcessor`` and we assert the
reconstructed top-N L2 book equals a hand-computed state at a checkpoint. The gold case is Kraken:
the reconstructed top-10 CRC32 must reproduce the fixture's ``checksum`` EXACTLY.
"""
from __future__ import annotations

from collections import defaultdict
from decimal import Decimal

from conftest import load_fixture
from test_recorders_kraken import _ORACLE_ASKS, _ORACLE_BIDS  # Kraken's REAL published worked input

from kbtc.normalize import extract, pipeline
from kbtc.normalize.checkpoint import METHOD_DEFERRED
from kbtc.recorders.base import ASK, BID, OrderIdBook, kraken_crc32
from kbtc.recorders.kraken import KrakenProcessor

T0 = 1_760_000_000_000_000_000


def _records(venue: str, name: str):
    for i, msg in enumerate(load_fixture(venue, name)):
        yield T0 + i, msg


def _snaps(rows: list[dict]) -> dict[int, list[tuple]]:
    out: dict[int, list[tuple]] = defaultdict(list)
    for b in rows:
        out[b["snap_id"]].append((b["side"], b["level"], str(b["price"]), str(b["size"])))
    return out


def _synced_by_snap(rows: list[dict]) -> dict[int, bool]:
    return {b["snap_id"]: b["synced"] for b in rows}


def _worked_example_snapshot(checksum: int) -> dict:
    """Kraken's published L3-guide worked example (21 bids / 14 asks) as a ``level3`` snapshot."""
    bids, asks, i = [], [], 0
    for px, qtys in _ORACLE_BIDS:
        for q in qtys:
            bids.append({"order_id": f"b{i}", "limit_price": px, "order_qty": q}); i += 1
    for px, qtys in _ORACLE_ASKS:
        for q in qtys:
            asks.append({"order_id": f"a{i}", "limit_price": px, "order_qty": q}); i += 1
    return {"channel": "level3", "type": "snapshot",
            "data": [{"symbol": "BTC/USD", "checksum": checksum, "bids": bids, "asks": asks}]}


# ---------------------------------------------------------------------------------------
# Kraken — CRC32 gold checkpoint (the real "matches venue snapshot at checkpoint").
# ---------------------------------------------------------------------------------------
def test_kraken_emit_path_reproduces_real_published_checksum():
    """GENUINE external acceptance (red-team #1/#3): run Kraken's REAL published worked-example
    book (checksum 1063832831 from the L3 guide) through the NORMALIZER, and assert its checkpoint
    reproduces that externally-published value — i.e. the book the normalizer emits from matches
    Kraken's own transmitted checksum (not a self-generated one)."""
    snap = _worked_example_snapshot(1063832831)
    res = pipeline.normalize_crypto("kraken", "level3", [(T0, snap)], levels=10)
    cp = res.checkpoint
    assert cp.method == "kraken_crc32"
    assert (cp.n_checkpoints, cp.n_matches, cp.n_mismatches) == (1, 1, 0)

    # The emitted top-N L2 is the faithful price aggregation of that externally-validated book:
    # the best bid (44939.4) sums the 8 orders resting at that price.
    bids = [r for r in _snaps(res.books)[1] if r[0] == "bid"]
    assert bids[0][2] == "44939.4"
    assert Decimal(bids[0][3]) == sum(Decimal(q) for q in _ORACLE_BIDS[0][1])
    # the snapshot establishes a complete baseline ⇒ synced True.
    assert _synced_by_snap(res.books)[1] is True


def test_kraken_fixture_checksum_is_a_regression_check_not_external():
    # NOTE: the fixture's checksums (843596241 / 1502863869) were SELF-GENERATED by kraken_crc32
    # when the fixture was authored, so this is a REGRESSION / self-consistency guard against
    # reconstruction drift — NOT the external oracle (that is the worked-example test above).
    msgs = load_fixture("kraken", "level3.jsonl")
    proc = KrakenProcessor(product="BTC/USD", depth=10)
    proc.process(msgs[0], T0)
    assert kraken_crc32(proc.book) == int(msgs[0]["data"][0]["checksum"]) == 843596241
    proc.process(msgs[1], T0 + 1)
    assert kraken_crc32(proc.book) == int(msgs[1]["data"][0]["checksum"]) == 1502863869


def test_kraken_checkpoint_report_counts_matches_and_the_seeded_mismatch():
    res = pipeline.normalize_crypto("kraken", "level3", _records("kraken", "level3.jsonl"))
    cp = res.checkpoint
    assert cp.method == "kraken_crc32"
    # 3 frames carry a checksum: snapshot + 2 updates. The 3rd update has a deliberately WRONG
    # checksum (999999999) → exactly one mismatch, two exact matches.
    assert (cp.n_checkpoints, cp.n_matches, cp.n_mismatches) == (3, 2, 1)
    assert cp.max_deviation == 0.0  # CRC is exact; magnitude is meaningless (match ⇒ 0)


def test_kraken_reconstruction_book_state():
    res = pipeline.normalize_crypto("kraken", "level3", _records("kraken", "level3.jsonl"))
    snaps = _snaps(res.books)
    # after the good update (snap 2): b3 added @99.8, b2 deleted; asks unchanged.
    assert snaps[2] == [
        ("bid", 0, "99.8", "0.5"), ("bid", 1, "99.5", "1.5"),
        ("ask", 0, "100.5", "1.0"), ("ask", 1, "101.0", "2.0"),
    ]


