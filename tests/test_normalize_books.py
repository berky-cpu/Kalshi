def test_synced_true_after_inband_snapshot_and_false_post_mismatch():
    # Kraken: snapshot (snap 1) + good update (snap 2) are synced; the checksum-mismatch snap (3)
    # is flagged synced=False (diverged, pre-resync) — not silently emitted as valid.
    kr = pipeline.normalize_crypto("kraken", "level3", _records("kraken", "level3.jsonl"))
    s = _synced_by_snap(kr.books)
    assert s[1] is True and s[2] is True and s[3] is False
    # Bybit: each snapshot (initial + mid-stream reset) re-establishes a complete baseline and the
    # intervening deltas are clean, so every emitted book is synced=True.
    by = pipeline.normalize_crypto("bybit", "perp", _records("bybit", "orderbook.jsonl"))
    assert all(v is True for v in _synced_by_snap(by.books).values())
